// Tests for the suffix fold in `tokenize()` (lib/bm25.mjs) and for what it does
// to `planning.mjs recall`. Run:
// node --test cadence-core/bin/planning-recall-fold.test.mjs
//
// WHY A COMMITTED FIXTURE CORPUS, and not this repository's live `.planning/`
// (D-05). The live corpus grows by every SUMMARY, UAT and CONTEXT a cycle
// writes, so pinning it reddens at every close for a reason that is not about
// the fold - the counter-case why-corpus.test.mjs already states about its own
// live tier. `fixtures/recall.corpus.json` is the corpus, and its rows are
// materialized through `makeTree` into a temp planning root, so what these arms
// rank over is the seam's real walk and not a hand-built index.
//
// WHY THE HITS ARE NAMED and never a byte-identical top 5 (D-04). The fold
// changes `df`, `idf` and the matched set by construction, so a golden-output
// comparison would go red the first time the fold correctly promotes a document
// and get weakened at the first task that hit it. `fixtures/recall.queries.json`
// therefore names, per query, the document ids that must be in that query's top
// 5. Every one of those lists was GENERATED by running the seam against the
// built root before the fold existed; an entry the fold moved out of the top 5
// carries a `changed_by_fold` string naming what moved, and nothing else in the
// file may change.
//
// The runner is `planning-recall.test.mjs`'s, imported and never copied: it
// pins `CADENCE_GLOBAL_CONFIG` off a nonexistent path so a developer's real
// global config cannot flip results locally while CI stays green.
//
// The two JSON files are read INSIDE the arms rather than at module load, so
// this module can be imported by a tool that is about to write one of them.
import { test } from 'node:test';
import assert from 'node:assert/strict';
import { readFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { makeTree } from './planning.test.mjs';
import { recall } from './planning-recall.test.mjs';

const FIXTURES = join(dirname(fileURLToPath(import.meta.url)), 'fixtures');

/** The committed fixture corpus: `[{id, source, text}]`. */
export function corpus() {
  return JSON.parse(readFileSync(join(FIXTURES, 'recall.corpus.json'), 'utf8'));
}

/** The committed query set: `[{query, hits, changed_by_fold?}]`. */
function queries() {
  return JSON.parse(readFileSync(join(FIXTURES, 'recall.queries.json'), 'utf8'));
}

/**
 * Materialize the fixture corpus into a temp `.planning` root and return its
 * path. The `source` field of each row is the exact string the seam must
 * return for it, so the mapping below is driven by that field alone and throws
 * on a source no tier builder covers - a silent miss here would put a document
 * in the wrong tier and weaken every arm downstream.
 *
 * Exported so the tool that regenerates `recall.queries.json` builds the SAME
 * tree these arms rank over; a baseline taken against a second, drifted builder
 * is not a no-regression claim.
 */
export function fixtureRoot() {
  const spec = { phases: {}, capture: [] };
  for (const doc of corpus()) {
    const m = doc.source.match(/^phases\/(\d+)\/(SUMMARY|CONTEXT)\.md$/);
    if (m) {
      const ph = (spec.phases[m[1]] ||= {});
      if (m[2] === 'SUMMARY') ((ph.summaryBody ||= {}).deviations ||= []).push(doc.text);
      else (ph.contextDecisions ||= []).push(doc.text);
      continue;
    }
    if (doc.source === 'CAPTURE.md') {
      spec.capture.push({ section: 'Notes', text: doc.text });
      continue;
    }
    throw new Error(`recall.corpus.json row ${doc.id} names a source no builder covers: ${doc.source}`);
  }
  return makeTree(spec);
}

/** The ids of `results`, in returned order, read out of each snippet. */
function idsOf(results) {
  return results.map((r) => (r.snippet.match(/\bzq\d+\b/) || ['?'])[0]);
}

// --- the fixture itself -------------------------------------------------------

test('fold fixture: every corpus document comes back under the source its row states', () => {
  const docs = corpus();
  assert.ok(docs.length >= 24, `the fixture corpus needs at least 24 documents, has ${docs.length}`);
  assert.ok(new Set(docs.map((d) => d.source)).size >= 3,
    'the fixture corpus needs at least three distinct `source` values');
  assert.equal(new Set(docs.map((d) => d.id)).size, docs.length, 'duplicate id in recall.corpus.json');

  const dir = fixtureRoot();
  // Five ids per call because `--top` defaults to 5 and the runner does not
  // pass it: an id is a term of exactly one document, so a batch of five is
  // exactly five scoring documents and the window cannot hide one.
  for (let k = 0; k < docs.length; k += 5) {
    const batch = docs.slice(k, k + 5);
    const r = recall(batch.map((d) => d.id).join(' '), dir);
    assert.equal(r.json.ok, true);
    assert.equal(r.json.results.length, batch.length,
      `ids ${batch.map((d) => d.id).join(' ')} matched ${r.json.results.length} documents, expected ${batch.length}`);
    for (const doc of batch) {
      const hit = r.json.results.find((x) => x.snippet.includes(doc.id));
      assert.ok(hit, `${doc.id} did not come back at all`);
      assert.equal(hit.source, doc.source, `${doc.id} came back under ${hit.source}`);
    }
  }
});

test('fold fixture: every committed query returns its named hits in the top 5', () => {
  const qs = queries();
  assert.ok(qs.length >= 10, `the fixture query set needs at least 10 entries, has ${qs.length}`);
  const dir = fixtureRoot();
  for (const q of qs) {
    assert.ok(Array.isArray(q.hits) && q.hits.length,
      `query ${JSON.stringify(q.query)} names no hits at all`);
    const r = recall(q.query, dir);
    assert.equal(r.json.ok, true);
    const got = idsOf(r.json.results);
    for (const id of q.hits) {
      assert.ok(got.includes(id),
        `query ${JSON.stringify(q.query)} lost ${id} from its top 5; got ${got.join(' ') || '(nothing)'}`);
    }
  }
});
