// Tests for the suffix fold in `tokenize()` (lib/bm25.mjs) and for what it does
// to `planning.mjs recall`. Run:
// node --test cadence-core/bin/planning-recall-fold.test.mjs
//
// WHY A COMMITTED FIXTURE CORPUS, and not this repository's live `.planning/`
// (D-05). The live corpus grows by every SUMMARY, UAT and CONTEXT a cycle
// writes, so pinning it reddens at every close for a reason that is not about
// the fold - the counter-case why-corpus.test.mjs already states about its own
// live tier. `fixtures/recall.corpus.json` is the corpus, and its rows are
// materialized through `makeTree` into a temp planning root, so what these arms
// rank over is the seam's real walk and not a hand-built index.
//
// WHY THE HITS ARE NAMED and never a byte-identical top 5 (D-04). The fold
// changes `df`, `idf` and the matched set by construction, so a golden-output
// comparison would go red the first time the fold correctly promotes a document
// and get weakened at the first task that hit it. `fixtures/recall.queries.json`
// therefore names, per query, the document ids that must be in that query's top
// 5. Every one of those lists was GENERATED by running the seam against the
// built root before the fold existed; an entry the fold moved out of the top 5
// carries a `changed_by_fold` string naming what moved, and nothing else in the
// file may change.
//
// The runner is `planning-recall.test.mjs`'s, imported and never copied: it
// pins `CADENCE_GLOBAL_CONFIG` off a nonexistent path so a developer's real
// global config cannot flip results locally while CI stays green.
//
// The two JSON files are read INSIDE the arms rather than at module load, so
// this module can be imported by a tool that is about to write one of them.
import { test } from 'node:test';
import assert from 'node:assert/strict';
import { readFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { tokenize } from './lib/bm25.mjs';
import { makeTree } from './planning.test.mjs';
import { recall } from './planning-recall.test.mjs';

const FIXTURES = join(dirname(fileURLToPath(import.meta.url)), 'fixtures');

/** The committed fixture corpus: `[{id, source, text}]`. */
export function corpus() {
  return JSON.parse(readFileSync(join(FIXTURES, 'recall.corpus.json'), 'utf8'));
}

/** The committed query set: `[{query, hits, changed_by_fold?}]`. */
function queries() {
  return JSON.parse(readFileSync(join(FIXTURES, 'recall.queries.json'), 'utf8'));
}

/**
 * Materialize the fixture corpus into a temp `.planning` root and return its
 * path. The `source` field of each row is the exact string the seam must
 * return for it, so the mapping below is driven by that field alone and throws
 * on a source no tier builder covers - a silent miss here would put a document
 * in the wrong tier and weaken every arm downstream.
 *
 * Exported so the tool that regenerates `recall.queries.json` builds the SAME
 * tree these arms rank over; a baseline taken against a second, drifted builder
 * is not a no-regression claim.
 */
export function fixtureRoot() {
  const spec = { phases: {}, capture: [] };
  for (const doc of corpus()) {
    const m = doc.source.match(/^phases\/(\d+)\/(SUMMARY|CONTEXT)\.md$/);
    if (m) {
      const ph = (spec.phases[m[1]] ||= {});
      if (m[2] === 'SUMMARY') ((ph.summaryBody ||= {}).deviations ||= []).push(doc.text);
      else (ph.contextDecisions ||= []).push(doc.text);
      continue;
    }
    if (doc.source === 'CAPTURE.md') {
      spec.capture.push({ section: 'Notes', text: doc.text });
      continue;
    }
    throw new Error(`recall.corpus.json row ${doc.id} names a source no builder covers: ${doc.source}`);
  }
  return makeTree(spec);
}

/** The ids of `results`, in returned order, read out of each snippet. */
function idsOf(results) {
  return results.map((r) => (r.snippet.match(/\bzq\d+\b/) || ['?'])[0]);
}

// --- the fixture itself -------------------------------------------------------

test('fold fixture: every corpus document comes back under the source its row states', () => {
  const docs = corpus();
  assert.ok(docs.length >= 24, `the fixture corpus needs at least 24 documents, has ${docs.length}`);
  assert.ok(new Set(docs.map((d) => d.source)).size >= 3,
    'the fixture corpus needs at least three distinct `source` values');
  assert.equal(new Set(docs.map((d) => d.id)).size, docs.length, 'duplicate id in recall.corpus.json');

  const dir = fixtureRoot();
  // Five ids per call because `--top` defaults to 5 and the runner does not
  // pass it: an id is a term of exactly one document, so a batch of five is
  // exactly five scoring documents and the window cannot hide one.
  for (let k = 0; k < docs.length; k += 5) {
    const batch = docs.slice(k, k + 5);
    const r = recall(batch.map((d) => d.id).join(' '), dir);
    assert.equal(r.json.ok, true);
    assert.equal(r.json.results.length, batch.length,
      `ids ${batch.map((d) => d.id).join(' ')} matched ${r.json.results.length} documents, expected ${batch.length}`);
    for (const doc of batch) {
      const hit = r.json.results.find((x) => x.snippet.includes(doc.id));
      assert.ok(hit, `${doc.id} did not come back at all`);
      assert.equal(hit.source, doc.source, `${doc.id} came back under ${hit.source}`);
    }
  }
});

test('fold fixture: every committed query returns its named hits in the top 5', () => {
  const qs = queries();
  assert.ok(qs.length >= 10, `the fixture query set needs at least 10 entries, has ${qs.length}`);
  const dir = fixtureRoot();
  for (const q of qs) {
    assert.ok(Array.isArray(q.hits) && q.hits.length,
      `query ${JSON.stringify(q.query)} names no hits at all`);
    const r = recall(q.query, dir);
    assert.equal(r.json.ok, true);
    const got = idsOf(r.json.results);
    for (const id of q.hits) {
      assert.ok(got.includes(id),
        `query ${JSON.stringify(q.query)} lost ${id} from its top 5; got ${got.join(' ') || '(nothing)'}`);
    }
  }
});

// --- the rule table, at tokenizer level ---------------------------------------
//
// These arms call `tokenize` directly, so the rule set is pinned independently
// of any corpus and a later "simplification" fails HERE rather than surfacing
// as a ranking regression nobody can read. Every row below was run before it
// was written down; a form outside steps 1a and 1b is deliberately left
// distinct and is not asserted as matching anything.

/** The single term one word tokenizes to. */
function folded(word) {
  const terms = tokenize(word);
  assert.equal(terms.length, 1, `${word} did not tokenize to exactly one term: ${JSON.stringify(terms)}`);
  return terms[0];
}

/** Assert a table of `[input, expected, why]` rows. */
function pinRows(rows) {
  for (const [input, expected, why] of rows) {
    assert.equal(folded(input), expected, `${input} -> ${folded(input)}, expected ${expected} (${why})`);
  }
}

test('fold rules: step 1a, and `es` is NOT a rule of its own', () => {
  pinRows([
    ['classes', 'class', 'sses -> ss'],
    ['passes', 'pass', 'sses -> ss'],
    ['carries', 'carri', 'ies -> i'],
    ['pass', 'pass', 'a final ss is kept'],
    ['seams', 'seam', 'an otherwise-final s is dropped'],
    ['notes', 'note', 'an otherwise-final s is dropped'],
    ['types', 'type', 'an otherwise-final s is dropped'],
    ['files', 'file', 'an otherwise-final s is dropped'],
    // The negative that closes D-02's refuted reading. An `es`-before-`s` rule
    // would give `clos` here, missing `close` - the roadmap's own worked
    // example - and splitting file/files, note/notes and type/types with it.
    ['closes', 'close', '`es` is never stripped as its own rule'],
  ]);
});

test('fold rules: step 1b strips ed and ing only over a stem with a vowel', () => {
  pinRows([
    ['walked', 'walk', '(*v*) ed -> ""'],
    ['counting', 'count', '(*v*) ing -> ""'],
    // No vowel in the stem, so neither strip fires and the word is left whole.
    ['bring', 'bring', 'the stem `br` holds no vowel'],
    ['ring', 'ring', 'the stem `r` holds no vowel'],
  ]);
});

test('fold rules: the eed guard turns on the measure of the stem before it', () => {
  pinRows([
    ['agreed', 'agree', 'the stem `agr` has measure 1, so eed -> ee'],
    ['freed', 'freed', 'the stem `fr` has measure 0, so eed is left alone'],
  ]);
});

test('fold rules: each of the three cleanup branches after a strip', () => {
  pinRows([
    ['gated', 'gate', 'a stem left ending `at` takes back an e'],
    ['troubling', 'trouble', 'a stem left ending `bl` takes back an e'],
    ['sizing', 'size', 'a stem left ending `iz` takes back an e'],
    ['planned', 'plan', 'a doubled final consonant loses a letter'],
    ['running', 'run', 'a doubled final consonant loses a letter'],
    ['spelling', 'spell', 'a doubled final l is the exception and is kept'],
    ['pulled', 'pull', 'a doubled final l is the exception and is kept'],
    ['named', 'name', 'a consonant-vowel-consonant stem takes back an e'],
    ['naming', 'name', 'a consonant-vowel-consonant stem takes back an e'],
    // Without this row the textbook `m == 1` gate would look harmless: with the
    // gate `refused` stops at `refus` while `refuse` stays `refuse`, and the
    // pair AC2 pins comes apart.
    ['refused', 'refuse', 'the m == 1 gate on that restoration is deliberately not applied'],
  ]);
});

test('fold rules: a base form is a fixed point, and a short token is untouched', () => {
  pinRows([
    ['seam', 'seam', 'nothing to fold'],
    ['close', 'close', 'nothing to fold'],
    ['note', 'note', 'nothing to fold'],
    ['type', 'type', 'nothing to fold'],
    ['file', 'file', 'nothing to fold'],
    ['name', 'name', 'nothing to fold'],
    ['refuse', 'refuse', 'nothing to fold'],
    ['plan', 'plan', 'nothing to fold'],
    // Two characters or fewer are returned whole: the s rule would otherwise
    // empty a one-letter token, and an empty term is one every document shares.
    ['us', 'us', 'a token of two characters is left alone'],
  ]);
});

// --- the equivalence groups, at the seam --------------------------------------
//
// The claim RCL-08 exists for, stated over the real walk: whichever member of
// an inflected group a user types, `recall` returns the same documents. Deep
// equality settles the returned window and equal `total` settles the whole
// matched set behind it, and the sharp arm is the last one - the document
// carrying ONLY another member's form has to be in the hits, or a group could
// pass by returning documents that already shared a literal term.

/** Every inflected group the fixture corpus carries a separate document for. */
const GROUPS = [
  ['seam', 'seams'],
  ['close', 'closes'],
  ['file', 'files'],
  ['note', 'notes'],
  ['type', 'types'],
  ['name', 'named', 'naming'],
  ['refuse', 'refused'],
  ['plan', 'planned'],
];

/** The id of the one fixture document whose text carries `word` literally. */
function docWithWord(docs, word) {
  const hits = docs.filter((d) => new RegExp(`\\b${word}\\b`).test(d.text));
  assert.equal(hits.length, 1,
    `the fixture corpus must carry exactly one document with the literal word \`${word}\`, found ${hits.length}`);
  return hits[0].id;
}

test('fold at the seam: each inflected group returns one and the same document set', () => {
  const docs = corpus();
  const dir = fixtureRoot();
  for (const group of GROUPS) {
    const owner = Object.fromEntries(group.map((w) => [w, docWithWord(docs, w)]));
    /** @type {{json:{results:Array<{snippet:string}>, total:number}}|null} */
    let first = null;
    for (const member of group) {
      const r = recall(member, dir);
      assert.equal(r.json.ok, true);
      // Non-empty first, or the deep equality below passes over two empty
      // arrays and the group asserts nothing at all.
      assert.ok(r.json.total >= 1, `query \`${member}\` matched nothing`);
      if (first === null) first = r;
      else {
        assert.deepEqual(r.json.results, first.json.results,
          `\`${member}\` and \`${group[0]}\` returned different results`);
        assert.equal(r.json.total, first.json.total,
          `\`${member}\` matched ${r.json.total} documents and \`${group[0]}\` matched ${first.json.total}`);
      }
      // The sharp arm: every OTHER member's exclusive document is in the hits.
      const got = idsOf(r.json.results);
      for (const other of group) {
        if (other === member) continue;
        assert.ok(got.includes(owner[other]),
          `query \`${member}\` did not return ${owner[other]}, the document that carries \`${other}\` and not \`${member}\`; got ${got.join(' ') || '(nothing)'}`);
      }
    }
  }
});
